export type AnalyticsLocale = keyof typeof analyticsCopy;
export function analyticsFormats(locale: AnalyticsLocale, currency = "USD") {
  const money = new Intl.NumberFormat(locale, { style: "currency", currency, minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const compactMoney = new Intl.NumberFormat(locale, { style: "currency", currency, notation: "compact", maximumFractionDigits: 1 });
  const number = new Intl.NumberFormat(locale);
  const percent = new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 2 });
  return {
    compactMoney: (cents: number) => compactMoney.format(cents / 100),
    money: (cents: number | null) => cents === null ? "—" : money.format(cents / 100),
    number: (value: number | null) => value === null ? "—" : number.format(value),
    percent: (value: number | null) => value === null ? "—" : percent.format(value),
  };
}
